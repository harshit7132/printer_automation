// Interactive setup: creates .env with encryption keys and the admin login.
// Usage: npm run setup            (first time)
//        npm run set-password     (change admin password; logs out all sessions)
// Non-interactive: SETUP_USER=admin SETUP_PASSWORD=... npm run setup
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import bcrypt from 'bcryptjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');
const passwordOnly = process.argv.includes('--password-only');

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    let v = m[2];
    if ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"'))) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

const env = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};

const rl = readline.createInterface({ input: process.stdin, output: process.stdout, terminal: process.stdin.isTTY });
let muted = false;
rl._writeToOutput = (s) => {
  if (!muted) return rl.output.write(s);
  // Hide typed password characters; only pass through the final newline.
  if (s.includes('\n') || s.includes('\r')) rl.output.write('\n');
};
const ask = (q) => new Promise((res) => rl.question(q, (a) => res(a.trim())));
async function askHidden(q) {
  rl.output.write(q);
  muted = true;
  const a = await new Promise((res) => rl.question('', res));
  muted = false;
  return a;
}

async function main() {
  console.log('\n=== e-Mitra Print Studio setup ===\n');
  if (passwordOnly && !env.MASTER_KEY) {
    console.log('No existing setup found. Running full setup instead.\n');
  }

  let user = process.env.SETUP_USER;
  let pass = process.env.SETUP_PASSWORD;
  if (!user) user = (await ask(`Admin username [${env.ADMIN_USER || 'admin'}]: `)) || env.ADMIN_USER || 'admin';
  if (!pass) {
    for (;;) {
      pass = await askHidden('Admin password (min 10 characters): ');
      if (pass.length < 10) { console.log('  Too short, try again.'); continue; }
      const again = await askHidden('Repeat password: ');
      if (again !== pass) { console.log('  Passwords do not match, try again.'); continue; }
      break;
    }
  } else if (pass.length < 10) {
    console.error('SETUP_PASSWORD must be at least 10 characters.');
    process.exit(1);
  }
  rl.close();

  env.ADMIN_USER = user.toLowerCase();
  env.ADMIN_PASS_HASH = await bcrypt.hash(pass, 12);
  if (!env.MASTER_KEY) env.MASTER_KEY = crypto.randomBytes(32).toString('hex');
  if (!env.SESSION_SECRET || passwordOnly) env.SESSION_SECRET = crypto.randomBytes(32).toString('hex');
  env.PORT ??= '3000';
  env.PUBLIC_URL ??= '';
  env.PRINT_MODE ??= 'auto';
  env.FILE_RETENTION_HOURS ??= '72';
  env.PII_RETENTION_DAYS ??= '90';
  env.TELEGRAM_BOT_TOKEN ??= '';
  env.TELEGRAM_CHAT_ID ??= '';

  const lines = [
    '# Generated by `npm run setup`. Keep this file private and backed up (MASTER_KEY decrypts your data).',
    ...Object.entries(env).map(([k, v]) => `${k}='${String(v).replace(/'/g, '')}'`),
    '',
  ];
  fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 });
  console.log(`\nSaved ${envPath}`);
  console.log(passwordOnly ? 'Password changed. All admin sessions were logged out.' : 'Setup complete. Start the app with:  npm start');
}

main().catch((e) => { console.error(e); process.exit(1); });
