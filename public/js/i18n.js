let lang = 'en';
try {
  lang = localStorage.getItem('lang') || '';
} catch { /* storage blocked */ }
if (!dict[lang]) lang = '';

export const hasSavedLang = () => !!lang;
export const getLang = () => lang || 'en';

export function t(key, vars = {}) {
  const s = dict[getLang()][key] ?? dict.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function apply(root = document) {
  document.documentElement.lang = getLang();
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}

export function setLang(l, save = true) {
  if (!dict[l]) return;
  lang = l;
  if (save) {
    try { localStorage.setItem('lang', l); } catch { /* ignore */ }
  }
  apply();
  window.dispatchEvent(new Event('langchange'));
}

/** Pick "en" or "hi" variant of a DB record field, e.g. pick(pkg, 'name'). */
export function pick(obj, field) {
  return (getLang() === 'hi' && obj[field + '_hi']) || obj[field + '_en'] || '';
}
